def extract_regions(text):
    """
    从文本中提取地区信息

    Args:
        text: 输入文本（标题+内容）

    Returns:
        dict: {'province': '省份', 'city': '城市', 'region_level': '地区级别'}
    """
    if not text:
        return None

    text = str(text).lower()
    result = {'province': None, 'city': None, 'region_level': None}

    # 首先检查城市（更具体）
    for province, cities in CITIES.items():
        for city in cities:
            if city in text:
                result['province'] = province.replace('市', '').replace('省', '').replace('自治区', '').replace('特别行政区', '')
                result['city'] = city
                result['region_level'] = '市'
                return result

    # 检查省份
    for province_short, province_full in PROVINCES.items():
        if province_short in text:
            result['province'] = province_short
            result['region_level'] = '省'
            return result

    return None


def batch_extract_regions(news_list):
    """
    批量提取地区信息

    Args:
        news_list: CollectedNews对象列表

    Returns:
        list: 更新后的news_list
    """
    for news in news_list:
        if not news.province and not news.city:  # 只提取未提取过的
            # 合并标题、摘要、内容来识别地区
            combined_text = ' '.join([
                news.title or '',
                news.summary or '',
                news.content or ''
            ])

            geo_info = extract_regions(combined_text)
            if geo_info:
                news.province = geo_info.get('province')
                news.city = geo_info.get('city')
                news.region_level = geo_info.get('region_level')

    return news_list
